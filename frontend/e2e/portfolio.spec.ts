import { test, expect } from '@playwright/test'

test('account, portfolio, citations state, saved settings and logout', async ({ page }) => {
  const email = `browser-${Date.now()}@example.com`
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Your name', { exact: true }).fill('Browser Investor')
  await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/dashboard$/)
  await expect(page.getByText('No holdings yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Add holding', exact: true }).click()
  await page.getByLabel('Find a stock', { exact: true }).fill('TCS')
  await page.getByRole('combobox', { name: 'Stock', exact: true }).selectOption('TCS')
  await page.getByLabel('Quantity', { exact: true }).fill('5')
  await page.getByLabel('Average purchase price (₹)', { exact: true }).fill('3000.50')
  await page.getByRole('button', { name: 'Save holding', exact: true }).click()
  await expect(page.getByText('5 shares · avg ₹3,000.50')).toBeVisible()
  await expect(page.getByText('no price', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('5 shares · avg ₹3,000.50')).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Quantity', { exact: true }).fill('7')
  await page.getByRole('button', { name: 'Save holding', exact: true }).click()
  await expect(page.getByText('7 shares · avg ₹3,000.50')).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../.local/portfolio-preview.png', fullPage: true })
  await page.getByRole('button', { name: /TCS.*7 shares/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByText('No assessment is available yet.', { exact: false })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByLabel('Account menu', {exact: true}).click()
  await page.getByRole('link', { name: 'Settings', exact: true }).first().click()
  await page.getByRole('button', { name: 'High only', exact: true }).click()
  await page.getByRole('switch', { name: 'Quiet market days', exact: true }).click()
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click()
  await expect(page.getByText('Preferences saved.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('switch', { name: 'Quiet market days', exact: true })).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('navigation', {name: 'Main', exact: true}).getByRole('link', { name: 'Stocks', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search stocks' }).fill('TCS')
  const tcsCard = page.locator('article').filter({ has: page.getByRole('button', { name: 'Add to watchlist: TCS', exact: true }) })
  await tcsCard.getByRole('button', { name: 'Add to watchlist: TCS', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remove from watchlist: TCS', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Watchlist', exact: true }).click()
  await expect(page.locator('article')).toHaveCount(1)
  await page.getByRole('link', { name: 'News & alerts', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'News & alerts', exact: true })).toBeVisible()
  await expect(page.getByText('No matching news yet')).toBeVisible()
  await page.getByRole('button', { name: 'Positive', exact: true }).click()
  await page.screenshot({ path: '../.local/news-preview.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: 'Portfolio', exact: true }).last().click()
  await expect(page.getByText('7 shares · avg ₹3,000.50')).toBeVisible()
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) {
    console.log(await page.evaluate(() => [...document.querySelectorAll('main *')].map(e => ({element: e.tagName, cls: e.className, right: e.getBoundingClientRect().right, width: e.getBoundingClientRect().width})).filter(e => e.right > innerWidth + 1)))
    await page.screenshot({path: '../.local/portfolio-overflow.png', fullPage: true})
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
  await page.screenshot({ path: '../.local/mobile-preview.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: 'Remove', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByText('No holdings yet.')).toBeVisible()
  await page.getByLabel('Account menu', {exact: true}).click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('mobile account form and guarded route remain usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/dashboard')
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible()
  const hasOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(hasOverflow).toBe(false)
})

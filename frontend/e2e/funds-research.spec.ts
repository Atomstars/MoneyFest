import { test, expect } from '@playwright/test'

test('track an AMFI scheme and inspect the research workspace on desktop and mobile', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Email', { exact: true }).fill(`fund-browser-${Date.now()}@example.com`)
  await page.getByLabel('Your name', { exact: true }).fill('Fund Investor')
  await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByRole('link', { name: 'Mutual funds', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Mutual funds' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search mutual funds' }).fill('Sample Banking Fund')
  await expect(page.getByText('Sample Banking Fund').first()).toBeVisible()
  await page.getByRole('button', { name: /Sample Banking Fund/ }).click()
  await page.getByLabel('Units', { exact: true }).fill('2')
  await page.getByLabel('Average purchase NAV', { exact: true }).fill('100')
  await page.getByRole('button', { name: 'Save to portfolio' }).click()
  await page.getByRole('button', { name: 'My funds · 1', exact: true }).click()
  await expect(page.getByText('2 units · NAV')).toBeVisible()
  await page.getByRole('navigation', {name: 'Main', exact: true}).getByRole('link', {name: 'Research', exact: true}).click()
  await page.getByRole('link', { name: 'Research desk', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Research desk' })).toBeVisible()
  await expect(page.getByText('AI research is not connected yet')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
  await page.getByRole('link', { name: 'Funds', exact: true }).last().click()
  await page.getByRole('button', { name: 'My funds · 1', exact: true }).click()
  await expect(page.getByText('2 units · NAV')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
  expect(errors).toEqual([])
})

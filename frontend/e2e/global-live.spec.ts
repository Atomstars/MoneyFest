import { test, expect } from '@playwright/test'

test('USD holdings and portfolio coach work through the real API', async ({ page }) => {
  test.skip(!process.env.E2E_URL?.endsWith(':5175'), 'Requires the dedicated MoneyFest test database server')
  await page.goto('/')
  await page.getByRole('button', {name: 'New here? Create an account'}).click()
  await page.getByLabel('Email', {exact: true}).fill(`global-browser-${Date.now()}@example.com`)
  await page.getByLabel('Your name', {exact: true}).fill('Global Test Investor')
  await page.getByLabel('Password', {exact: true}).fill('browser-password-123')
  await page.getByRole('button', {name: 'Create account', exact: true}).click()
  await page.getByRole('button', {name: 'US · USD', exact: true}).click()
  await page.getByRole('button', {name: 'Add holding', exact: true}).click()
  await page.getByLabel('Find a stock', {exact: true}).fill('AAPL')
  await page.getByRole('combobox', {name: 'Stock', exact: true}).selectOption('AAPL.US')
  await page.getByLabel('Quantity', {exact: true}).fill('1.5')
  await page.getByLabel('Average purchase price ($)', {exact: true}).fill('100')
  await page.getByRole('button', {name: 'Save holding', exact: true}).click()
  await expect(page.getByText('1.5 shares · avg $100.00')).toBeVisible()
  await expect(page.getByText('$150', {exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'India · INR', exact: true}).click()
  await expect(page.getByText('No holdings yet.', {exact: true})).toBeVisible()
  await page.goto('/portfolio-lab')
  await expect(page.getByRole('button', {name: 'Save draft', exact: true})).toBeEnabled()
  await page.getByLabel('Market & currency').selectOption('USD')
  await page.getByRole('button', {name: 'Import holdings', exact: true}).click()
  await expect(page.getByLabel('Target weight for AAPL', {exact: true})).toHaveValue('100')
  await page.getByLabel('Target weight for AAPL').fill('50')
  await page.getByRole('button', {name: 'Discuss plan', exact: true}).click()
  await page.getByLabel('Discuss this portfolio').fill('How should I compare these weights?')
  await page.getByRole('button', {name: 'Save & ask agent'}).click()
  await expect(page.locator('.plan-assistant .assistant-answer')).toContainText('Rules-based review of your saved draft: 1 stocks in USD, 50% allocated.')
  await expect(page.locator('.plan-assistant .assistant-answer')).toContainText('Largest position: AAPL at 50%')
  await page.reload()
  await expect(page.getByLabel('Target weight for AAPL')).toHaveValue('50')
  await page.getByRole('link', {name: 'AAPL ↗', exact: true}).click()
  await expect(page.getByText('Insufficient data', {exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'Trade planner', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Trade mechanism', exact: true})).toBeVisible()
})
